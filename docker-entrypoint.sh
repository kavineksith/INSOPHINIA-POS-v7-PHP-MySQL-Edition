#!/bin/bash
# ============================================================================
# INSOPHINIA POS v7 — Docker Entrypoint
# ----------------------------------------------------------------------------
# Runs before Apache starts. Responsibilities:
#   1. Generate config/config.php from environment variables (if missing)
#   2. Wait for MySQL to be reachable
#   3. Verify install.sql has been applied (auto-applied by MySQL image on
#      first boot via /docker-entrypoint-initdb.d/)
#   4. Run seed.php (idempotent — safe to run every container start)
#   5. Ensure storage/ directories are writable by www-data
#   6. Exec the main process (Apache)
# ============================================================================

set -e

echo "============================================================"
echo "  INSOPHINIA POS v7 — Docker entrypoint"
echo "  Time: $(date -u '+%Y-%m-%d %H:%M:%S UTC')"
echo "============================================================"

# ---- 1. Generate config/config.php from env vars ----
CONFIG_FILE=/var/www/html/config/config.php
if [ ! -f "$CONFIG_FILE" ]; then
    echo "→ Generating config/config.php from environment variables..."
    cat > "$CONFIG_FILE" <<PHP_EOF
<?php
/**
 * INSOPHINIA POS v7 — Configuration (auto-generated by Docker entrypoint)
 * Edit environment variables in docker-compose.yml / .env to change these.
 */

return [
    'app_name'      => 'INSOPHINIA POS v7',
    'app_env'       => getenv('APP_ENV') ?: 'production',
    'debug'         => filter_var(getenv('APP_DEBUG') ?: 'false', FILTER_VALIDATE_BOOL),
    'app_url'       => getenv('APP_URL') ?: 'http://localhost:8080',
    'app_timezone'  => getenv('APP_TIMEZONE') ?: 'Asia/Colombo',

    'db' => [
        'host'      => getenv('DB_HOST') ?: 'mysql',
        'port'      => (int)(getenv('DB_PORT') ?: 3306),
        'name'      => getenv('DB_NAME') ?: 'insophinia_pos',
        'user'      => getenv('DB_USER') ?: 'insophinia',
        'pass'      => getenv('DB_PASS') ?: '',
        'charset'   => 'utf8mb4',
        'collation' => 'utf8mb4_unicode_ci',
        'options'   => [
            PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            PDO::ATTR_EMULATE_PREPARES   => false,
            PDO::ATTR_PERSISTENT         => false,
        ],
    ],

    'jwt_secret'        => getenv('JWT_SECRET') ?: 'CHANGE_ME_IN_PRODUCTION',
    'jwt_expiration'    => (int)(getenv('JWT_EXPIRATION') ?: 3600),
    'jwt_algorithm'     => 'HS256',

    'bcrypt_rounds'     => (int)(getenv('BCRYPT_ROUNDS') ?: 12),
    'password_min_len'  => 12,
    'password_max_len'  => 30,

    'cookie_secure'     => filter_var(getenv('COOKIE_SECURE') ?: 'false', FILTER_VALIDATE_BOOL),
    'cookie_samesite'   => 'Strict',
    'cookie_domain'     => '',
    'cookie_path'       => '/',

    'csrf_token_length' => 32,
    'csrf_cookie_name'  => 'csrf_token',
    'csrf_header_name'  => 'X-CSRF-Token',
    'csrf_lifetime'     => 3600,

    'rate_limit' => [
        'default_max'      => 100,
        'default_window_ms'=> 60000,
        'endpoints' => [
            'login'           => ['max' => 5,  'window_ms' => 15 * 60 * 1000, 'event' => 'LOGIN_FAILED'],
            'password_change' => ['max' => 3,  'window_ms' => 15 * 60 * 1000, 'event' => 'SUSPICIOUS_ACTIVITY'],
            'marketing_send'  => ['max' => 5,  'window_ms' => 60 * 60 * 1000, 'event' => 'SUSPICIOUS_ACTIVITY'],
            'warranty_claim'  => ['max' => 10, 'window_ms' => 60 * 60 * 1000, 'event' => 'SUSPICIOUS_ACTIVITY'],
        ],
    ],

    'max_request_body_size' => 1048576,
    'session_lifetime'      => 3600,
    'session_throttle_activity_ms' => 60000,
    'token_rotation_age_seconds'   => 1800,
    'lockout_threshold'            => 5,
    'lockout_duration_sec'         => 900,

    'email' => [
        'enabled'   => filter_var(getenv('EMAIL_ENABLED') ?: 'false', FILTER_VALIDATE_BOOL),
        'host'      => getenv('EMAIL_HOST') ?: 'smtp.example.com',
        'port'      => (int)(getenv('EMAIL_PORT') ?: 587),
        'username'  => getenv('EMAIL_USERNAME') ?: '',
        'password'  => getenv('EMAIL_PASSWORD') ?: '',
        'secure'    => getenv('EMAIL_SECURE') ?: 'tls',
        'from'      => getenv('EMAIL_FROM') ?: 'INSOPHINIA <noreply@insophinia.lk>',
        'timeout_connection' => 10,
        'timeout_greeting'   => 10,
        'timeout_socket'     => 15,
    ],

    'whatsapp_enabled' => true,

    'storage' => [
        'temp_pdfs' => __DIR__ . '/../storage/temp_pdfs',
        'logs'      => __DIR__ . '/../storage/logs',
        'cache'     => __DIR__ . '/../storage/cache',
    ],

    'temp_pdf' => [
        'ttl_seconds'   => 600,
        'max_entries'   => 100,
        'key_length'    => 16,
    ],

    'marketing_bulk_cap' => 500,

    'settings_allowed_prefixes'  => ['shop_', 'bill_', 'email_', 'whatsapp_', 'vat_', 'sscl_', 'loyalty_'],
    'settings_blocked_key_regex' => '/password|secret|api[_-]?key/i',

    'seed' => [
        'admin_username' => getenv('SEED_ADMIN_USERNAME') ?: 'master',
        'admin_password' => getenv('SEED_ADMIN_PASSWORD') ?: 'Master@Admin123!',
        'admin_email'    => getenv('SEED_ADMIN_EMAIL') ?: 'master@insophinia.lk',
    ],
];
PHP_EOF
    echo "  ✓ config.php generated"
else
    echo "→ config/config.php already exists — keeping existing"
fi

# ---- 2. Ensure storage directories exist & are writable ----
echo "→ Ensuring storage directories are writable..."
mkdir -p /var/www/html/storage/temp_pdfs \
         /var/www/html/storage/logs \
         /var/www/html/storage/cache
chown -R www-data:www-data /var/www/html/storage
chmod -R 775 /var/www/html/storage
echo "  ✓ storage/ ready"

# ---- 3. Install Composer deps if missing (e.g. when storage volume is fresh) ----
if [ ! -d /var/www/html/vendor ]; then
    echo "→ vendor/ missing — running composer install..."
    cd /var/www/html
    composer install --no-dev --optimize-autoloader --no-interaction || {
        echo "  ⚠ Composer install failed — app may not work properly"
    }
    echo "  ✓ Composer dependencies installed"
fi

# ---- 4. Wait for MySQL to be reachable ----
DB_HOST="${DB_HOST:-mysql}"
DB_PORT="${DB_PORT:-3306}"
DB_USER="${DB_USER:-insophinia}"
DB_PASS="${DB_PASS:-}"
DB_NAME="${DB_NAME:-insophinia_pos}"

echo "→ Waiting for MySQL at ${DB_HOST}:${DB_PORT}..."
MAX_WAIT=60
WAITED=0
while [ $WAITED -lt $MAX_WAIT ]; do
    if mysqladmin ping -h "$DB_HOST" -P "$DB_PORT" -u "$DB_USER" -p"$DB_PASS" --silent 2>/dev/null; then
        echo "  ✓ MySQL is reachable (after ${WAITED}s)"
        break
    fi
    WAITED=$((WAITED + 2))
    sleep 2
done
if [ $WAITED -ge $MAX_WAIT ]; then
    echo "  ⚠ MySQL not reachable after ${MAX_WAIT}s — continuing anyway (seed will fail if DB is down)"
fi

# ---- 5. Verify schema is loaded (auto-applied on first MySQL boot) ----
echo "→ Verifying database schema..."
TABLE_COUNT=$(mysql -h "$DB_HOST" -P "$DB_PORT" -u "$DB_USER" -p"$DB_PASS" "$DB_NAME" \
    -sN -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema = '$DB_NAME';" 2>/dev/null || echo "0")
if [ "$TABLE_COUNT" -lt 24 ]; then
    echo "  ⚠ Only ${TABLE_COUNT}/24 tables found. Importing install.sql manually..."
    mysql -h "$DB_HOST" -P "$DB_PORT" -u "$DB_USER" -p"$DB_PASS" "$DB_NAME" < /var/www/html/install.sql 2>&1 | tail -5 || true
    echo "  ✓ Schema import attempted"
else
    echo "  ✓ Schema verified (${TABLE_COUNT} tables present)"
fi

# ---- 6. Run seeder (idempotent — safe on every start) ----
echo "→ Running database seeder..."
cd /var/www/html
php seed.php 2>&1 | sed 's/^/  /' || echo "  ⚠ Seeder reported errors (may be normal if already seeded)"

# ---- 7. Final permission fix (in case volume mounts reset ownership) ----
chown -R www-data:www-data /var/www/html/storage /var/www/html/config
chmod 640 /var/www/html/config/config.php

echo "============================================================"
echo "  ✓ Setup complete — starting Apache"
echo "  Login: ${SEED_ADMIN_USERNAME:-master} / ${SEED_ADMIN_PASSWORD:-Master@Admin123!}"
echo "============================================================"

# ---- 8. Exec the main process (Apache) ----
exec "$@"
